# Asking user for to input two numbers
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

# Calculation and printing the result
print(f"The sum of {num1} and {num2} is: {num1 + num2}") # Addition
print(f"The difference of {num1} and {num2} is: {num1 - num2}") # Subtraction
print(f"The product of {num1} and {num2} is: {num1 * num2}") # Multiplication
print(f"The quotient of {num1} and {num2} is: {num1 / num2}") # Division